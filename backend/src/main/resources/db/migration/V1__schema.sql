-- CareDesk schema. Plain SQL that runs on both PostgreSQL and H2 (PostgreSQL mode).

create table service_offering (
    id               bigint generated by default as identity primary key,
    name             varchar(120)   not null,
    description      varchar(500),
    duration_minutes integer        not null,
    price            numeric(10, 2) not null,
    active           boolean        not null default true,
    constraint ck_service_duration check (duration_minutes > 0),
    constraint ck_service_price check (price >= 0)
);

create table staff (
    id        bigint generated by default as identity primary key,
    full_name varchar(120) not null,
    title     varchar(120) not null,
    email     varchar(160),
    bio       varchar(500),
    active    boolean      not null default true
);

create table staff_service (
    staff_id   bigint not null references staff (id),
    service_id bigint not null references service_offering (id),
    primary key (staff_id, service_id)
);

create table working_hours (
    id          bigint generated by default as identity primary key,
    staff_id    bigint      not null references staff (id),
    day_of_week varchar(10) not null,
    start_time  time        not null,
    end_time    time        not null,
    constraint ck_working_hours_range check (start_time < end_time)
);

create index idx_working_hours_staff on working_hours (staff_id);

create table appointment (
    id                   bigint generated by default as identity primary key,
    reference            varchar(12)  not null,
    staff_id             bigint       not null references staff (id),
    service_id           bigint       not null references service_offering (id),
    start_time           timestamp    not null,
    end_time             timestamp    not null,
    status               varchar(16)  not null,
    customer_name        varchar(120) not null,
    customer_email       varchar(160) not null,
    customer_phone       varchar(32),
    notes                varchar(500),
    created_at           timestamp    not null,
    confirmation_sent_at timestamp,
    reminder_sent_at     timestamp,
    constraint uq_appointment_reference unique (reference),
    constraint ck_appointment_range check (start_time < end_time)
);

create index idx_appointment_staff_start on appointment (staff_id, start_time);
create index idx_appointment_start on appointment (start_time);

-- One row per 15-minute block that a live (not cancelled) appointment occupies.
-- The unique key is the database-level guard against double booking: two
-- appointments can never hold the same block of the same staff member, even if
-- two requests race past the application check. Cancelling deletes the rows,
-- which frees the time again.
create table booked_block (
    id             bigint    generated by default as identity primary key,
    appointment_id bigint    not null references appointment (id) on delete cascade,
    staff_id       bigint    not null references staff (id),
    block_start    timestamp not null,
    constraint uq_booked_block_staff_start unique (staff_id, block_start)
);

create index idx_booked_block_appointment on booked_block (appointment_id);

create table app_user (
    id            bigint generated by default as identity primary key,
    email         varchar(160) not null,
    display_name  varchar(120) not null,
    password_hash varchar(100) not null,
    role          varchar(16)  not null,
    constraint uq_app_user_email unique (email)
);

create table email_log (
    id             bigint generated by default as identity primary key,
    appointment_id bigint references appointment (id) on delete set null,
    kind           varchar(16)   not null,
    recipient      varchar(160)  not null,
    subject        varchar(200)  not null,
    body           varchar(4000) not null,
    status         varchar(16)   not null,
    error          varchar(500),
    created_at     timestamp     not null
);

create index idx_email_log_created on email_log (created_at);
